/**
 * Where this month is heading.
 *
 * The projection is split into two parts that are reported separately rather than
 * merged into one confident number:
 *
 *   committed — subscriptions that will definitely be charged before month end
 *   variable  — everyday spending, extrapolated from the daily average so far
 *
 * The first is near-certain; the second is a guess that is wildly unreliable early
 * in the month, when three days of coffee become a thirty-day trend. Keeping them
 * apart lets the UI show the certain part plainly and hedge the rest.
 */

import type { SqlDatabase } from '../db/adapter.js';
import { type CurrencyCode } from '../money/currency.js';
import { type Money, money } from '../money/money.js';
import {
  type IsoDate,
  addDays,
  daysBetween,
  endOfMonth,
  monthKey,
  startOfMonth,
} from '../time/date.js';
import { type MonthKey, type SpendTotals, monthTotal } from './budget.js';
import { estimateInBase } from './rates.js';
import { occurrencesBetween } from './recurrence.js';
import type { ExpenseRepository } from './repository.js';

export interface MonthForecast {
  readonly month: MonthKey;
  readonly asOf: IsoDate;
  readonly spentSoFar: SpendTotals;
  /** Scheduled charges still to come this month. */
  readonly committed: Money;
  /** Everyday spending projected over the remaining days. */
  readonly variable: Money;
  readonly projectedTotal: Money;
  readonly daysElapsed: number;
  readonly daysRemaining: number;
  /**
   * Rules whose cost in the base currency is unknown, so they are missing from
   * `committed`. The projection is a floor while this is non-empty.
   */
  readonly rulesWithoutRate: readonly string[];
  /**
   * True when the daily average rests on too few days of actual spending to mean
   * anything. The UI should present the variable part as a hint, not a number.
   */
  readonly variableUnreliable: boolean;
  /** Distinct days with everyday spending. The basis for the projection. */
  readonly daysWithSpending: number;
  /** Everyday spend per elapsed day, shown so the projection can be judged. */
  readonly dailyAverage: Money;
}

export interface ForecastOptions {
  readonly baseCurrency?: CurrencyCode;
  /**
   * Distinct spending days below which the projection is flagged unreliable.
   *
   * Counting *days with spending* rather than days elapsed is what catches the
   * case that matters: entering a month of back-dated expenses in one sitting
   * looks like a huge daily rate, when it is really one day of data.
   */
  readonly minDaysForTrend?: number;
}

export const DEFAULT_MIN_DAYS_FOR_TREND = 7;

export function forecastMonth(
  repo: ExpenseRepository,
  db: SqlDatabase,
  asOf: IsoDate,
  options: ForecastOptions = {},
): MonthForecast {
  const baseCurrency = options.baseCurrency ?? repo.baseCurrency;
  const minDays = options.minDaysForTrend ?? DEFAULT_MIN_DAYS_FOR_TREND;

  const month = monthKey(asOf);
  const monthStart = startOfMonth(asOf);
  const monthEnd = endOfMonth(asOf);

  const daysElapsed = daysBetween(monthStart, asOf) + 1;
  const daysRemaining = daysBetween(asOf, monthEnd);

  const spentSoFar = monthTotal(db, month, baseCurrency);

  // Variable spend excludes anything generated by a rule, since those are counted
  // in `committed`; including both would double-count every subscription.
  const variableRow = db.get<{ total: number | null }>(
    `SELECT SUM(base_amount_minor) AS total
       FROM expense
      WHERE deleted_at IS NULL
        AND recurring_rule_id IS NULL
        AND occurred_on >= ? AND occurred_on <= ?`,
    [monthStart, asOf],
  );
  const variableSoFar = variableRow?.total ?? 0;
  const dailyAverage = daysElapsed > 0 ? variableSoFar / daysElapsed : 0;

  const spendingDaysRow = db.get<{ days: number }>(
    `SELECT COUNT(DISTINCT occurred_on) AS days
       FROM expense
      WHERE deleted_at IS NULL
        AND recurring_rule_id IS NULL
        AND base_amount_minor IS NOT NULL
        AND occurred_on >= ? AND occurred_on <= ?`,
    [monthStart, asOf],
  );
  const daysWithSpending = spendingDaysRow?.days ?? 0;

  let committed = 0;
  const rulesWithoutRate: string[] = [];

  if (daysRemaining > 0) {
    for (const rule of repo.listRules('active')) {
      const occurrences = occurrencesBetween(
        rule,
        // Charges dated today are already in `spentSoFar` if they were logged.
        addDays(asOf, 1),
        monthEnd,
      );
      if (occurrences.length === 0) continue;

      const valued =
        rule.amount.currency === baseCurrency
          ? { value: rule.amount }
          : estimateInBase(db, rule.amount, baseCurrency, rule.id);

      if (!valued) {
        rulesWithoutRate.push(rule.id);
        continue;
      }
      committed += valued.value.amountMinor * occurrences.length;
    }
  }

  const variable = Math.round(dailyAverage * daysRemaining);

  return {
    month,
    asOf,
    spentSoFar,
    committed: money(committed, baseCurrency),
    variable: money(variable, baseCurrency),
    projectedTotal: money(spentSoFar.total.amountMinor + committed + variable, baseCurrency),
    daysElapsed,
    daysRemaining,
    rulesWithoutRate,
    variableUnreliable: daysWithSpending < minDays,
    daysWithSpending,
    dailyAverage: money(Math.round(dailyAverage), baseCurrency),
  };
}
